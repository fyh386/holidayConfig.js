    /* ===================== 查询 API ===================== */

    function pad2(n) { return (n < 10 ? '0' : '') + n; }

    // Date -> 'yyyyMMdd'
    function ymd(d) {
        return '' + d.getFullYear() + pad2(d.getMonth() + 1) + pad2(d.getDate());
    }

    /**
     * 判断当前日期的类型
     * @returns {number} 0: 工作日，1: 双休日（非调休上班），2: 法定节假日
     */
    Date.prototype.isHoliday = function () {
        var y = '' + this.getFullYear(), key = ymd(this);
        var holidays = HOLIDAYS[y], workdays = WORKDAYS[y];
        if (holidays && holidays[key]) return 2;
        var day = this.getDay();
        if (day === 0 || day === 6) {
            if (workdays && workdays.indexOf(key) !== -1) return 0;
            return 1;
        }
        return 0;
    };

    /**
     * 当天节日名（如 '春节'），非节假日返回 null
     * @returns {string|null}
     */
    Date.prototype.holidayName = function () {
        var holidays = HOLIDAYS['' + this.getFullYear()];
        return (holidays && holidays[ymd(this)]) || null;
    };

    /**
     * 在当前日期基础上加减 num 个工作日（会修改并返回 this）
     * @param {number} num 正数向后、负数向前
     * @returns {Date}
     */
    Date.prototype.getWorkday = function (num) {
        var step = num > 0 ? 1 : -1, count = Math.abs(num) || 0;
        for (var i = 0; i < count; i++) {
            do { this.setDate(this.getDate() + step); } while (this.isHoliday() !== 0);
        }
        return this;
    };

    /**
     * 将 Date 转化为指定格式的字符串（meizz 版）
     * 月(M)、日(d)、小时(h)、分(m)、秒(s)、季度(q) 可用 1-2 个占位符，
     * 年(y) 可用 1-4 个占位符，毫秒(S) 只能用 1 个占位符（1-3 位数字）
     * 例子：(new Date()).Format('yyyy-MM-dd hh:mm:ss.S') -> 2006-07-02 08:09:04.423
     */
    Date.prototype.Format = function (fmt) {
        var o = {
            'M+': this.getMonth() + 1,
            'd+': this.getDate(),
            'h+': this.getHours(),
            'm+': this.getMinutes(),
            's+': this.getSeconds(),
            'q+': Math.floor((this.getMonth() + 3) / 3),
            'S': this.getMilliseconds()
        };
        if (/(y+)/.test(fmt)) {
            fmt = fmt.replace(RegExp.$1, (this.getFullYear() + '').substr(4 - RegExp.$1.length));
        }
        for (var k in o) {
            if (new RegExp('(' + k + ')').test(fmt)) {
                fmt = fmt.replace(RegExp.$1, RegExp.$1.length === 1 ? o[k] : ('00' + o[k]).substr(('' + o[k]).length));
            }
        }
        return fmt;
    };

